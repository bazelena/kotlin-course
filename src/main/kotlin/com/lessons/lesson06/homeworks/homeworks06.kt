/*
Задание 4: "Расчет бонусных баллов"
Клиенты интернет-магазина получают бонусные баллы за покупки.
Напишите функцию, которая принимает сумму покупки и печатает в консоль
количество бонусных баллов: 2 балла за каждые 100 рублей при сумме покупки до 1000 рублей и 3 балла за каждые 100 рублей при сумме свыше этого.
 */
fun bonusPoints(ball: Int) {
    val hundreds = ball / 100
    val points = if (ball <= 1000) hundreds * 2 else hundreds * 3
    println("Количество бонусных баллов: $points")
}

