/*
. Преобразование строк
Создайте функцию, которая будет анализировать входящие фразы и применять к ним различные преобразования,
делая текст более ироничным или забавным. Функция должна уметь распознавать ключевые слова или условия и соответственно изменять фразу.

Правила проверки и преобразования:

Если фраза содержит слово "невозможно":
Преобразование: Замените "невозможно" на "совершенно точно возможно, просто требует времени".
Если фраза начинается с "Я не уверен":
Преобразование: Добавьте в конец фразы ", но моя интуиция говорит об обратном".
Если фраза содержит слово "катастрофа":
Преобразование: Замените "катастрофа" на "интересное событие".
Если фраза заканчивается на "без проблем":
Преобразование: Замените "без проблем" на "с парой интересных вызовов на пути".
Если фраза содержит только одно слово:
Преобразование: Добавьте перед словом "Иногда," и после слова ", но не всегда".
Примеры Тестовых Фраз:

"Это невозможно выполнить за один день"
"Я не уверен в успехе этого проекта"
"Произошла катастрофа на сервере"
"Этот код работает без проблем"
"Удача"
 */
fun example1(phrase: String) {
    val result = when {
        phrase.contains("невозможно") -> phrase.replace("невозможно", "совершенно точно возможно, просто требует времени")
        phrase.startsWith("Я не уверен", ignoreCase = true) -> phrase + ", но моя интуиция говорит об обратном"
        phrase.contains("катастрофа") -> phrase.replace("катастрофа", "интересное событие")
        phrase.endsWith("без проблем", ignoreCase = true) -> phrase.replace("без проблем", "с парой интересных вызовов на пути")
        !phrase.contains(" ") -> "Иногда, $phrase, но не всегда"
        else -> phrase
    }
    println(result)
}

/*
2. Извлечение даты из строки лога
У вас есть строка лога, например "Пользователь вошел в систему -> 2021-12-01 09:48:23" (данные могут быть любыми, но формат всегда такой).
Извлеките отдельно дату и время из этой строки и сразу распечатай их по очереди. Используй indexOf или split для получения правой части сообщения.
 */
fun example2(phrase: String) {
    val rightPart = phrase.split(" -> ")[1]   // всё, что после " -> "
    val date = rightPart.split(" ")[0]         // дата — до пробела
    val time = rightPart.split(" ")[1]         // время — после пробела

    println(date)
    println(time)
}

/*
3. Маскирование личных данных
Дана строка с номером кредитной карты, например "4539 1488 0343 6467". Замаскируйте все цифры, кроме последних четырех, символами "*".
*/
fun example3(phrase: String) {
    val lastFour = phrase.takeLast(4)
    val maskedPart = phrase.dropLast(4).map { if (it.isDigit()) '*' else it }.joinToString("")
    println(maskedPart + lastFour)
}

/*
4. Форматирование адреса электронной почты.
У вас есть электронный адрес, например "username@example.com".
Преобразуйте его в строку "username [at] example [dot] com", используя функцию replace()
*/
fun example4(phrase: String) {
    val result = phrase
        .replace("@", " [at] ")
        .replace(".", " [dot] ")
    println(result)
}

/*
5. Извлечение имени файла из пути.
Дан путь к файлу, например "C:/Пользователи/Документы/report.txt" или "D:/good.themes/dracula.theme" (может быть любым).
Извлеките название файла с расширением.
*/
fun example5(phrase: String) {
    val fileName = phrase.substringAfterLast("/")
    println(fileName)
}

/*
6. У вас есть фраза, например "Котлин лучший язык программирования" (может быть любой с разделителями слов - пробел).
Создайте аббревиатуру из начальных букв слов (например, "ООП").
Используйте split. Используйте for для перебора слов. Используйте var переменную для накопления первых букв.
 */
fun example6(phrase: String) {
    val words = phrase.split(" ")   // разбиваем фразу на список слов
    var abbreviation = ""            // переменная-накопитель для букв аббревиатуры
    for (word in words) {            // перебираем каждое слово в списке
        abbreviation += word.first().uppercaseChar()  // добавляем первую букву слова (в верхнем регистре)
    }
    println(abbreviation)
}

